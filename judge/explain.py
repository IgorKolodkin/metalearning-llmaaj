"""The jury explanation, rendered from the same rulebook and check results that eval uses.

Everything that can change with the solution (rules, checker prompt, models, prediction code, adapt
thresholds) is read from the running code and data here, not restated by hand, so the explanation
stays true after any change to the judge.
"""
import inspect
import json
import re
from collections import Counter
from itertools import combinations

from . import adapt, data, executor, rulebook
from .data import first_user_text
from .executor import CHECK_MODEL, CHECK_SYSTEM, fired, predict
from .rulebook import digest, rule_text

THIN = 2  # a rule backed by this many expert-bad train conversations or fewer is flagged as thin
SHOWN = 2  # bad examples shown per rule
# checker evidence saying the rule's situation never came up in the conversation
NOT_IN_PLAY = re.compile(r"not applicable|does not arise|never ask|never push|no user push|only asked|there is no|stated no|"
                         r"did not ask|not about", re.I)


def _source(obj):
    try:
        return inspect.getsource(obj).rstrip()
    except (OSError, TypeError):
        return f"# source of {getattr(obj, '__name__', obj)} unavailable"


def _bad_hits(mat, rid, by_id):
    return [i for i, r in mat.get(rid, {}).items() if r["violated"] and by_id[i]["label"] == "bad"]


def _pick_examples(hits, mat, shown):
    """Prefer conversations where only this rule fires, then ones not shown under another rule."""
    return sorted(hits, key=lambda i: (len(fired(mat, i)) > 1, i in shown, i))[:SHOWN]


def _contrast(bad, goods, row, tries=10):
    """The most similar expert-good conversation where the rule was in play, not merely inapplicable.

    The check result keeps only the evidence, so "in play" is read from its wording; if none of the
    nearest goods qualifies, the nearest one is shown anyway.
    """
    pool = [g for g in goods if g["topic"] == bad["topic"] and g["item_id"] in row]
    ranked = []
    while pool and len(ranked) < tries:
        g = adapt.nearest_good(bad, pool)
        ranked.append(g)
        pool.remove(g)
    for g in ranked:
        if not NOT_IN_PLAY.search(row[g["item_id"]]["evidence"]):
            return g
    return ranked[0] if ranked else None


def _rejection(h, accepted_ids, mat):
    if (h["round"], h["id"]) in accepted_ids:
        return f"another proposal for {h['id']} was accepted in the same round"
    broken = ", ".join(f"`{i}`" for i in h["broken"])
    if len(h["broken"]) > adapt.MAX_BREAK:
        return f"would label {len(h['broken'])} expert-good conversation(s) bad: {broken}"
    if h["broken"] and len(h["fixed"]) <= len(h["broken"]):
        return f"would fix {len(h['fixed'])} but label {len(h['broken'])} expert-good bad ({broken}): no net gain"
    if not h["fixed"]:
        covering = sorted({rid for i in h.get("proposed_fixes", []) for rid in fired(mat, i)})
        by = f" ({', '.join(covering)} fire on the conversations it targeted)" if covering else ""
        return "redundant: the errors it targeted were already fixed by accepted rules" + by
    return f"fixed {len(h['fixed'])} but did not pass the acceptance threshold"


def render(book, mat, train):
    by_id = {it["item_id"]: it for it in train}
    pred = predict(mat, train)
    correct = sum(pred[i] == it["label"] for i, it in by_id.items())
    rules = book["rules"]
    n_bad = sum(it["label"] == "bad" for it in train)
    hits = {r["id"]: _bad_hits(mat, r["id"], by_id) for r in rules}
    goods_hit = {r["id"]: [i for i, x in mat.get(r["id"], {}).items()
                           if x["violated"] and by_id[i]["label"] == "good"] for r in rules}

    out = [
        "# How this judge labels conversations",
        "",
        f"Generated by `python -m judge adapt` in the same run that wrote `rulebook.json` next to this file "
        f"(rulebook version `{digest(book)}`, {len(rules)} rules, learned from {len(train)} labeled "
        f"training conversations, {n_bad} of them bad). `eval` reads only `rulebook.json`; this file is not "
        "used for prediction. Every rule below is quoted exactly as the checker receives it, and every number "
        "comes from the same check results that produce the labels "
        "(see \"How to verify\" at the end).",
        "",
        "## Decision procedure and priorities",
        "",
        f"1. Each rule is checked separately: one check per (rule, conversation) by `{CHECK_MODEL}` "
        f"(effort `{executor.CHECK_EFFORT}`), which returns `applicable`, `violated` and `evidence`.",
        "2. A rule is checked only on conversations of the topics it applies to. "
        "A rule that is not applicable to a conversation counts as not violated.",
        "3. **A conversation is `bad` if at least one applicable rule is violated, otherwise `good`.** "
        "All rules have equal weight: any single violation outweighs every other quality of the answer "
        "(length, tone, links, completeness beyond the rules). Two violations are not \"more bad\" than one.",
        "4. The whole conversation is judged: a violation in any assistant turn makes it `bad`.",
        "5. A defect that no rule describes does not make a conversation `bad` (see Boundaries).",
        "",
        f"On the {len(train)} training conversations this procedure agrees with the expert on {correct}.",
        "",
        "## Rules at a glance",
        "",
        "| rule | applies to | fires on train (expert bad / expert good) |",
        "|---|---|---|",
    ]
    for r in rules:
        topics = "all topics" if "*" in r["topics"] else ", ".join(r["topics"])
        out.append(f"| {r['id']}: {r['name']} | {topics} | {len(hits[r['id']])} / {len(goods_hit[r['id']])} |")

    out += ["", "## Rules, with training examples", "",
            "Bad examples are the training conversations where the rule fired; conversations where only this "
            "rule fires are shown first. The contrast example is a similar expert-good conversation of the same "
            "topic (the word-overlap similarity adapt uses) where the rule's situation comes up, with what the "
            "checker found there.", ""]
    shown = set()
    goods = [it for it in train if it["label"] == "good"]
    for rule in rules:
        rid, row = rule["id"], mat.get(rule["id"], {})
        out += ["```", rule_text(rule), "```", "",
                f"On train: fires on {len(hits[rid])} expert-bad and {len(goods_hit[rid])} expert-good conversations.",
                ""]
        picked = _pick_examples(hits[rid], mat, shown)
        for i in picked:
            others = [x for x in fired(mat, i) if x != rid]
            also = f" Also violates {', '.join(others)}." if others else ""
            out.append(f"- `{i}` (expert: **bad**) user asked: \"{first_user_text(by_id[i])}\". "
                       f"Violation found: {row[i]['evidence']}{also}")
        shown.update(picked)
        if picked:
            good = _contrast(by_id[picked[0]], goods, row)
            if good:
                out.append(f"- Contrast: `{good['item_id']}` (expert: **good**) user asked: "
                           f"\"{first_user_text(good)}\". Checker found no violation: {row[good['item_id']]['evidence']}")
        else:
            out.append("- Fires on no expert-bad training conversation.")
        out.append("")

    out += _boundaries(book, mat, train, by_id, pred, hits, rules)
    out += _mechanism(book, mat, train, correct)
    return "\n".join(out)


def _boundaries(book, mat, train, by_id, pred, hits, rules):
    out = ["## Boundaries: where this judge is less reliable", ""]
    misses = [i for i, it in by_id.items() if it["label"] == "bad" and pred[i] == "good"]
    false_bads = [i for i, it in by_id.items() if it["label"] == "good" and pred[i] == "bad"]
    out += ["### Disagreements with the expert on train", ""]
    if not misses and not false_bads:
        out.append(f"None: all {len(train)} training labels are reproduced. That only means the rules fit the "
                   "training set; the conditions below are where new conversations are most likely to be mislabeled.")
    for i in misses:
        out.append(f"- `{i}` expert: **bad**, judge: good. No rule explains this label; "
                   f"user asked: \"{first_user_text(by_id[i])}\".")
    for i in false_bads:
        why = "; ".join(f"{rid}: {mat[rid][i]['evidence']}" for rid in fired(mat, i))
        out.append(f"- `{i}` expert: **good**, judge: bad. The expert tolerates this: {why}")
    out.append("")

    thin = [r for r in rules if len(hits[r["id"]]) <= THIN]
    if thin:
        out += ["### Rules backed by few examples", "",
                f"These rules rest on {THIN} or fewer expert-bad training conversations, so their wording "
                "generalizes from very little evidence and may be too narrow or too broad on new data:", ""]
        for r in thin:
            ids = ", ".join(f"`{i}`" for i in hits[r["id"]]) or "none"
            out.append(f"- {r['id']}: {r['name']} ({len(hits[r['id']])}: {ids})")
        out.append("")

    pairs = Counter()
    shared = {}
    for i, it in by_id.items():
        if it["label"] == "bad":
            for a, b in combinations(sorted(fired(mat, i)), 2):
                pairs[a, b] += 1
                shared.setdefault((a, b), []).append(i)
    if pairs:
        names = {r["id"]: r["name"] for r in rules}
        out += ["### Rules that overlap", "",
                "These rules fire on the same bad conversations. The label is unaffected (one violation is enough), "
                "but the line between the two rules is blurred, so either may fire on a new conversation:", ""]
        for (a, b), n in pairs.most_common():
            ids = ", ".join(f"`{i}`" for i in shared[a, b][:3])
            out.append(f"- {a} ({names[a]}) and {b} ({names[b]}): {n} shared, e.g. {ids}")
        out.append("")

    tolerated = [h for h in book["history"] if h.get("op") in ("add", "edit") and not h.get("accepted")
                 and h.get("broken")]
    if tolerated:
        out += ["### Where the expert draws the line", "",
                "Candidate rules that adapt rejected because they also flagged conversations the expert labeled "
                "good. Where an accepted rule covers the same defect, its checker evidence on that conversation "
                "shows what separates the tolerated case from the violation:", ""]
        for h in tolerated:
            covering = sorted({rid for i in h["fixed"] for rid in fired(mat, i)})
            for i in h["broken"]:
                if i not in by_id:
                    continue
                line = (f"- Rejected \"{h['name']}\" would have flagged `{i}` (expert: **good**), "
                        f"user asked: \"{first_user_text(by_id[i])}\".")
                for rid in covering:
                    if i in mat.get(rid, {}):
                        line += f" Accepted {rid}, which catches the same bad conversations, finds no violation " \
                                f"here: {mat[rid][i]['evidence']}"
                out.append(line)
        out.append("")

    n_bad = sum(it["label"] == "bad" for it in train)
    out += ["### Defects outside the rules", "",
            f"The judge only knows the {len(rules)} rules above. A conversation with a defect none of them "
            f"describes is labeled `good`, however wrong the answer. On train {n_bad - len(misses)} of {n_bad} "
            "expert-bad conversations are explained by at least one rule; expert requirements not represented "
            "in the training data cannot be caught.",
            ""]
    return out


def _mechanism(book, mat, train, correct):
    out = ["## How the rules were learned", "",
           f"`adapt` applies the current rules to train, shows every misjudged conversation (a missed bad next to "
           f"its most similar good) to `{adapt.PROPOSE_MODEL}`, which proposes adding, editing or removing rules. "
           f"Each proposal is checked on all of train and accepted only if it fixes at least {adapt.MIN_FIX} "
           f"error(s) and mislabels at most {adapt.MAX_BREAK} correctly judged conversation(s); "
           f"up to {adapt.MAX_ROUNDS} rounds.", ""]
    hist = [h for h in book["history"] if "accepted" in h]
    accepted_ids = {(h["round"], h["id"]) for h in hist if h["accepted"]}
    if hist:
        out += ["| round | proposal | target | outcome |", "|---|---|---|---|"]
        for h in hist:
            broke = f", mislabeled {len(h['broken'])} good" if h["broken"] else ""
            outcome = (f"accepted, fixed {len(h['fixed'])}{broke}" if h["accepted"]
                       else "rejected: " + _rejection(h, accepted_ids, mat))
            out.append(f"| {h['round']} | {h['op']} \"{h['name']}\" | {h['id']} | {outcome} |")
        out.append("")

    out += ["## How prediction works, and how to verify this file", "",
            "The checker gets this system instruction verbatim:", "", "```", CHECK_SYSTEM, "```", "",
            "and must answer with this JSON schema:", "", "```json",
            json.dumps(executor.CHECK_SCHEMA, indent=1), "```", "",
            "The code below is quoted from the running source at the moment this file was generated. "
            "`data.render` and `rulebook.rule_text` build the request, `executor.check` sends one request per "
            "(rule, conversation), `executor.predict` turns the results into labels.", ""]
    for obj in (data.render, rulebook.rule_text, executor.check, executor.fired, executor.predict,
                rulebook.digest):
        out += ["```python", _source(obj), "```", ""]
    out += ["To verify:", "",
            f"- `rulebook.digest` of `rulebook.json` is `{digest(book)}`, and each rule text above equals "
            "`rule_text` of the same rule in that file;",
            "- `python -m judge eval --test <file> --artifacts <this folder>` predicts with exactly these rules;",
            f"- on the training file, `predict` over these rules gives {correct} of {len(train)} expert labels and "
            "the per-rule counts in the table above.",
            ""]
    return out
